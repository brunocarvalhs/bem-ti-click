function inside(lon, lat, poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

let cached = null;
// Desenha o mapa uma vez (MAP_W × MAP_H pixels) e devolve como imagem PNG.
export function worldMapImage() {
  if (cached) return cached;
  const land = new Uint8Array(MAP_W * MAP_H);
  for (let y = 0; y < MAP_H; y++) for (let x = 0; x < MAP_W; x++) {
    const lon = MAP.lonMin + (x + 0.5) * MAP.deg, lat = MAP.latMax - (y + 0.5) * MAP.deg;
    land[y * MAP_W + x] = LAND.some(p => inside(lon, lat, p)) ? 1 : 0;
  }
  const c = document.createElement('canvas'); c.width = MAP_W; c.height = MAP_H;
  const g = c.getContext('2d');
  const at = (x, y) => x >= 0 && y >= 0 && x < MAP_W && y < MAP_H && land[y * MAP_W + x];
  for (let y = 0; y < MAP_H; y++) for (let x = 0; x < MAP_W; x++) {
    const coast = at(x, y) && !(at(x + 1, y) && at(x - 1, y) && at(x, y + 1) && at(x, y - 1));
    const nearLand = !at(x, y) && (at(x + 1, y) || at(x - 1, y) || at(x, y + 1) || at(x, y - 1));
    g.fillStyle = at(x, y) ? (coast ? '#3f7d3a' : (x + y) % 7 === 0 ? '#5e9a4c' : '#6fae5a') : nearLand ? '#2f6a9a' : (x + y * 3) % 11 === 0 ? '#245a86' : '#1d4f7a';
    g.fillRect(x, y, 1, 1);
  }
  cached = c.toDataURL('image/png');
  return cached;
}
